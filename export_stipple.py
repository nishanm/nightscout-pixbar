"""Export what Track B's Stipple fork takes from this repo, in the forms its build wants.

    python export_stipple.py <path-to-Stipple-repo>

Writes, under that repo:

    firmware/tests/testdata/glucose-<face>--<state>.rgb   one per golden frame: raw RGB888,
                                                          row-major, the exact bytes of
                                                          Stipple's Framebuffer::bytes()
    firmware/tests/support/GlucoseGoldenInputs.h          the manifest's inputs (every state's
                                                          reading and full history) as C++
    firmware/include/stipple/apps/GlucoseFontData.h       fonts.py and the 3x5 fallback as C++

Why a separate exporter from export_fonts.py: that one emits C for any firmware; this one
emits what Stipple's C++17 build compiles warning-free (typed constexpr tables, no void
pointers), plus the test corpus in Stipple's fixture format. Both are pure transformations
of fonts.py / golden/, so nothing here is a second source of truth.

Every .rgb is decoded from its golden PNG and its SHA-256 checked against the manifest
before anything is written, so this script cannot drift from make_golden.py: if the corpus
moves, `make_golden.py --check` fails first, and this refuses a frame whose hash disagrees.
"""

import hashlib
import json
import os
import struct
import sys
import zlib

import fonts as _F
import render as R
from export_fonts import c_ident

HERE = os.path.dirname(os.path.abspath(__file__))
GOLDEN = os.path.join(HERE, "golden")
MANIFEST = os.path.join(GOLDEN, "manifest.json")

FONTS = [
    ("Hero", _F.SPLEEN_12X24, _F.SPLEEN_12X24_W, _F.SPLEEN_12X24_H),
    ("Mid", _F.SPLEEN_8X16, _F.SPLEEN_8X16_W, _F.SPLEEN_8X16_H),
    ("Small", _F.SPLEEN_6X12, _F.SPLEEN_6X12_W, _F.SPLEEN_6X12_H),
]


# ------------------------------------------------------------------ PNG -> RGB888
def png_to_rgb888(data, w, h):
    """Decode the 1:1 golden PNGs render.png_bytes writes: 8-bit RGB, filter 0 on every
    row, one or more IDAT chunks. Anything else is refused rather than guessed at."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos, idat = 8, []
    while pos < len(data):
        (length,) = struct.unpack(">I", data[pos:pos + 4])
        tag = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + length]
        if tag == b"IHDR":
            pw, ph, depth, ctype = struct.unpack(">IIBB", body[:10])
            if (pw, ph, depth, ctype) != (w, h, 8, 2):
                raise ValueError(f"unexpected IHDR {pw}x{ph} depth={depth} type={ctype}")
        elif tag == b"IDAT":
            idat.append(body)
        pos += 12 + length
    raw = zlib.decompress(b"".join(idat))
    stride = 1 + 3 * w
    if len(raw) != stride * h:
        raise ValueError(f"decoded {len(raw)} bytes, expected {stride * h}")
    out = bytearray()
    for y in range(h):
        row = raw[y * stride:(y + 1) * stride]
        if row[0] != 0:
            raise ValueError(f"row {y} uses filter {row[0]}, only 0 is handled")
        out += row[1:]
    return bytes(out)


# ------------------------------------------------------------------ fixtures + inputs
def export_goldens(repo):
    with open(MANIFEST, encoding="utf-8") as fh:
        manifest = json.load(fh)
    w, h = manifest["panel"]["width"], manifest["panel"]["height"]
    testdata = os.path.join(repo, "firmware", "tests", "testdata")
    os.makedirs(testdata, exist_ok=True)

    states = {}   # state name -> inputs (identical across faces, asserted)
    frames = []
    for e in manifest["frames"]:
        with open(os.path.join(GOLDEN, e["file"]), "rb") as fh:
            rgb = png_to_rgb888(fh.read(), w, h)
        digest = hashlib.sha256(rgb).hexdigest()
        if digest != e["sha256_rgb888"]:
            raise SystemExit(f"{e['file']}: decoded hash {digest[:12]} != manifest "
                             f"{e['sha256_rgb888'][:12]} - corpus and PNG disagree, refusing")
        name = f"glucose-{e['face']}--{e['state']}"
        with open(os.path.join(testdata, name + ".rgb"), "wb") as fh:
            fh.write(rgb)
        inputs = e["inputs"]
        if e["state"] in states and states[e["state"]] != inputs:
            raise SystemExit(f"state {e['state']} has different inputs on different faces")
        states[e["state"]] = inputs
        frames.append((e["face"], e["state"], name, e["lit_pixels"]))

    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by nightscout-pixbar/export_stipple.py from golden/manifest.json - do not edit.",
        "//",
        "// The inputs behind every golden frame, so the firmware renderer is tested against",
        "// exactly what the reference renderer drew. Histories are copied verbatim rather",
        "// than regenerated: the reference builds them with float arithmetic, and a second",
        "// implementation of that would be a second thing to get wrong.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace stipple {",
        "namespace apps {",
        "namespace glucose {",
        "namespace golden {",
        "",
        "struct Point {",
        "    std::int64_t epoch;",
        "    int sgv;",
        "};",
        "",
        "struct State {",
        "    const char* name;",
        "    int sgv;",
        "    const char* trend;",
        "    bool hasDelta;",
        "    int delta;",
        "    int minutesAgo;",
        "    int hour;",
        "    int minute;",
        "    bool stale;",
        "    const Point* history;",
        "    int historyCount;",
        "};",
        "",
        "struct Frame {",
        "    const char* face;",
        "    const char* state;",
        "    const char* fixture;",
        "    int litPixels;",
        "};",
        "",
        f"inline constexpr std::int64_t kFixedNow = {manifest['fixed_now']};",
        f"inline constexpr int kStaleMinutes = {manifest['stale_minutes']};",
        "",
    ]
    for name, inputs in states.items():
        ident = name.replace("-", "_")
        pts = ", ".join(f"{{{int(e)}, {int(v)}}}" for e, v in inputs["history"])
        out.append(f"inline constexpr Point kHistory_{ident}[] = {{{pts}}};")
    out.append("")
    out.append(f"inline constexpr int kStateCount = {len(states)};")
    out.append("inline constexpr State kStates[kStateCount] = {")
    for name, inputs in states.items():
        ident = name.replace("-", "_")
        hh, mm = (int(p) for p in inputs["time"].split(":"))
        delta = inputs["delta"]
        out.append(
            f'    {{"{name}", {inputs["sgv"]}, "{inputs["trend"]}", '
            f'{"true" if delta is not None else "false"}, {delta if delta is not None else 0}, '
            f'{inputs["minutes_ago"]}, {hh}, {mm}, {"true" if inputs["stale"] else "false"}, '
            f'kHistory_{ident}, {len(inputs["history"])}}},')
    out.append("};")
    out.append("")
    out.append(f"inline constexpr int kFrameCount = {len(frames)};")
    out.append("inline constexpr Frame kFrames[kFrameCount] = {")
    for face, state, name, lit in frames:
        out.append(f'    {{"{face}", "{state}", "{name}", {lit}}},')
    out.append("};")
    out += ["", "}  // namespace golden", "}  // namespace glucose", "}  // namespace apps",
            "}  // namespace stipple", ""]
    path = os.path.join(repo, "firmware", "tests", "support", "GlucoseGoldenInputs.h")
    write(path, out)
    print(f"wrote {len(frames)} fixtures to {testdata} and {path}")


# ------------------------------------------------------------------ fonts
def glyph_ink(rows):
    c0, c1, r0, r1 = R.ink_box(rows)
    return (-1, -1, -1, -1) if c1 < c0 else (c0, c1, r0, r1)


def export_fonts(repo):
    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by nightscout-pixbar/export_stipple.py from fonts.py and render.py - do not edit.",
        "//",
        "// Spleen (c) 2018-2026 Frederic Cambus, BSD-2-Clause. Only the glyphs a glucose face",
        "// can show are included. Rows run top to bottom; within a row the LEFTMOST pixel is",
        "// bit (width - 1). c0/c1/r0/r1 are the inked column and row bounds (-1 for a blank",
        "// glyph such as space), precomputed so the text engine trims to ink without scanning.",
        "// The 3x5 fallback (kTiny) is variable-width: its width is c1 + 1.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace stipple {",
        "namespace apps {",
        "namespace glucose {",
        "namespace fontdata {",
        "",
        "struct Glyph {",
        "    char ch;",
        "    const std::uint16_t* rows;",
        "    std::int8_t c0;",
        "    std::int8_t c1;",
        "    std::int8_t r0;",
        "    std::int8_t r1;",
        "};",
        "",
        "struct Font {",
        "    int width;",
        "    int height;",
        "    int count;",
        "    const Glyph* glyphs;",
        "};",
        "",
        "namespace rows {",
        "",
    ]
    tables = []
    for name, table, w, h in FONTS:
        lname = name.lower()
        for ch, rws in table.items():
            assert len(rws) == h and all(len(r) == w for r in rws), (name, ch)
            masks = ", ".join(f"0x{int(r, 2):0{(w + 3) // 4}X}" for r in rws)
            out.append(f"inline constexpr std::uint16_t {lname}_{c_ident(ch)}[{h}] = {{{masks}}};")
        out.append("")
        tables.append((name, lname, table, w, h))
    tiny = R._T
    for ch, rws in tiny.items():
        masks = ", ".join(f"0x{int(r, 2):02X}" for r in rws)
        out.append(f"inline constexpr std::uint16_t tiny_{c_ident(ch)}[{R.TINY_H}] = {{{masks}}};")
    out += ["", "}  // namespace rows", ""]

    for name, lname, table, w, h in tables:
        out.append(f"inline constexpr Glyph k{name}Glyphs[{len(table)}] = {{")
        for ch, rws in table.items():
            c0, c1, r0, r1 = glyph_ink(rws)
            lit = "'\\''" if ch == "'" else f"'{ch}'"
            out.append(f"    {{{lit}, rows::{lname}_{c_ident(ch)}, {c0}, {c1}, {r0}, {r1}}},")
        out.append("};")
        out.append(f"inline constexpr Font k{name}{{{w}, {h}, {len(table)}, k{name}Glyphs}};")
        out.append("")
    out.append(f"inline constexpr Glyph kTinyGlyphs[{len(tiny)}] = {{")
    for ch, rws in tiny.items():
        w = len(rws[0])
        lit = "'\\''" if ch == "'" else f"'{ch}'"
        out.append(f"    {{{lit}, rows::tiny_{c_ident(ch)}, 0, {w - 1}, 0, {R.TINY_H - 1}}},")
    out.append("};")
    out.append(f"inline constexpr Font kTiny{{3, {R.TINY_H}, {len(tiny)}, kTinyGlyphs}};")
    out += ["", "}  // namespace fontdata", "}  // namespace glucose", "}  // namespace apps",
            "}  // namespace stipple", ""]
    path = os.path.join(repo, "firmware", "include", "stipple", "apps", "GlucoseFontData.h")
    write(path, out)
    print(f"wrote {path}")


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))


def main(argv):
    if len(argv) != 2 or not os.path.isdir(os.path.join(argv[1], "firmware")):
        print(__doc__)
        return 2
    repo = os.path.abspath(argv[1])
    export_goldens(repo)
    export_fonts(repo)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
