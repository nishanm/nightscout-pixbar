"""Export the baked fonts, arrow bitmaps, palette and thresholds as C headers.

    python export_fonts.py          # writes export/fonts.h and export/palette.h

For Track B (our own firmware on the TC002). The firmware must draw the same glyphs
as this renderer, so it gets them from the same table rather than from Spleen's BDFs
again: fonts.py is the single source, this script is a pure transformation of it, and
the golden corpus (make_golden.py) is the test that the two agree.

Layout of a glyph: rows top to bottom, each row a bit mask with the LEFTMOST pixel in
the most significant used bit (bit W-1). Glyphs are the full font cell; ink trimming
(render.py's glyph_boxes / _ink_top) is layout logic the firmware reimplements from
the same rules, which is why the ink box of every glyph is also emitted as data.

Spleen (c) 2018-2026 Frederic Cambus, BSD-2-Clause - notice carried into the header.
"""

import os

import fonts as _F
import render as R

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "export")

FONTS = [
    ("SPLEEN_12X24", _F.SPLEEN_12X24, _F.SPLEEN_12X24_W, _F.SPLEEN_12X24_H, "HERO"),
    ("SPLEEN_8X16", _F.SPLEEN_8X16, _F.SPLEEN_8X16_W, _F.SPLEEN_8X16_H, "MID"),
    ("SPLEEN_6X12", _F.SPLEEN_6X12, _F.SPLEEN_6X12_W, _F.SPLEEN_6X12_H, "SMALL"),
]


def c_ident(ch):
    names = {":": "COLON", ".": "DOT", ",": "COMMA", "-": "MINUS", "+": "PLUS",
             "%": "PERCENT", "?": "QUESTION", "/": "SLASH", " ": "SPACE", "'": "APOS"}
    return names.get(ch, ch)


def row_mask(row):
    return int(row, 2)


def ink_box(rows):
    cols = [c for c in range(len(rows[0])) if any(r[c] == "1" for r in rows)]
    inked = [i for i, r in enumerate(rows) if "1" in r]
    if not cols:
        return -1, -1, -1, -1
    return cols[0], cols[-1], inked[0], inked[-1]


def emit_font(out, name, table, w, h, role):
    rtype = "uint8_t" if w <= 8 else "uint16_t"
    out.append(f"/* {name}: {w}x{h} cell, role {role}, {len(table)} glyphs */")
    out.append(f"#define {name}_W {w}")
    out.append(f"#define {name}_H {h}")
    out.append(f"#define {name}_COUNT {len(table)}")
    for ch, rows in table.items():
        assert len(rows) == h and all(len(r) == w for r in rows), (name, ch)
        masks = ", ".join(f"0x{row_mask(r):0{(w + 3) // 4}X}" for r in rows)
        out.append(f"static const {rtype} {name}_{c_ident(ch)}[{h}] = {{{masks}}};")
    out.append(f"static const glyph_t {name}_GLYPHS[{name}_COUNT] = {{")
    for ch, rows in table.items():
        c0, c1, r0, r1 = ink_box(rows)
        out.append(f"    {{ '{ch}', {name}_{c_ident(ch)}, {c0}, {c1}, {r0}, {r1} }},")
    out.append("};")
    out.append("")


def emit_bitmap_set(out, name, table, w):
    out.append(f"/* {name}: {w} px wide, one per BG_TREND */")
    for trend, rows in table.items():
        masks = ", ".join(f"0x{row_mask(r):02X}" for r in rows)
        out.append(f"static const uint8_t {name}_{trend}[{len(rows)}] = {{{masks}}};")
    out.append("")


def write_fonts_h():
    out = [
        "/* Generated by export_fonts.py from fonts.py - do not edit.",
        " *",
        " * Spleen (c) 2018-2026 Frederic Cambus, BSD-2-Clause. Only the glyphs a glucose",
        " * face can show are included. Row bit masks: leftmost pixel = bit (W-1).",
        " * ink_c0/c1/r0/r1 are the glyph's inked column/row bounds (-1 = blank glyph,",
        " * e.g. space) so the firmware can trim to ink exactly as render.py does.",
        " */",
        "#ifndef PIXBAR_FONTS_H",
        "#define PIXBAR_FONTS_H",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    char ch;",
        "    const void *rows;   /* uint8_t[H] for W<=8 fonts, uint16_t[H] otherwise */",
        "    int8_t ink_c0, ink_c1, ink_r0, ink_r1;",
        "} glyph_t;",
        "",
        "/* Layout constants shared with render.py: 1 px tracking between trimmed glyphs,",
        " * a blank glyph advances 3 px. */",
        "#define PIXBAR_TRACKING 1",
        "#define PIXBAR_SPACE_ADVANCE 3",
        "",
    ]
    for name, table, w, h, role in FONTS:
        emit_font(out, name, table, w, h, role)
    # the 3x5 fallback font and the two arrow sets, from render.py
    tiny = {ch: rows for ch, rows in R._T.items()}
    out.append("/* TINY: 3x5 fallback (variable width: '.' ',' ':' are 1 wide, space 2) */")
    out.append(f"#define TINY_H {R.TINY_H}")
    for ch, rows in tiny.items():
        w = len(rows[0])
        masks = ", ".join(f"0x{row_mask(r):02X}" for r in rows)
        out.append(f"static const uint8_t TINY_{c_ident(ch)}[{R.TINY_H}] = {{{masks}}}; /* w={w} */")
    out.append("")
    emit_bitmap_set(out, "ARROW7", R.ARROWS, R.ARROW_W)
    emit_bitmap_set(out, "ARROW5", R.ARROWS5, R.ARROW5_W)
    out.append("#endif /* PIXBAR_FONTS_H */")
    out.append("")
    return "\n".join(out)


def write_palette_h():
    import faces as F
    def c(t):
        return f"{{{t[0]}, {t[1]}, {t[2]}}}"
    out = [
        "/* Generated by export_fonts.py from render.py / faces.py - do not edit.",
        " * Colours are the TC001 firmware's RGB565 constants expanded to RGB888 exactly",
        " * as render.rgb565_to_rgb does (r*255/31, g*255/63, b*255/31, integer). */",
        "#ifndef PIXBAR_PALETTE_H",
        "#define PIXBAR_PALETTE_H",
        "#include <stdint.h>",
        "",
        "typedef struct { uint8_t r, g, b; } rgb_t;",
        "",
        f"#define PIXBAR_W {R.W}",
        f"#define PIXBAR_H {R.H}",
        "",
        f"static const rgb_t PX_BLACK   = {c(R.BLACK)};",
        f"static const rgb_t PX_BLUE    = {c(R.BLUE)};",
        f"static const rgb_t PX_GREEN   = {c(R.GREEN)};",
        f"static const rgb_t PX_CYAN    = {c(R.CYAN)};",
        f"static const rgb_t PX_GRAY    = {c(R.GRAY)};",
        f"static const rgb_t PX_RED     = {c(R.RED)};",
        f"static const rgb_t PX_MAGENTA = {c(R.MAGENTA)};",
        f"static const rgb_t PX_YELLOW  = {c(R.YELLOW)};",
        f"static const rgb_t PX_WHITE   = {c(R.WHITE)};",
        "",
        "/* the value's colour IS the glucose state */",
        "#define BG_NORMAL  PX_GREEN",
        "#define BG_WARNING PX_YELLOW",
        "#define BG_URGENT  PX_RED",
        "#define BG_STALE   PX_GRAY",
        "",
        "/* thresholds, mg/dL, as the owner's clocks run them */",
        f"#define URGENT_LOW  {F.URGENT_LOW}",
        f"#define WARN_LOW    {F.WARN_LOW}",
        f"#define WARN_HIGH   {F.WARN_HIGH}",
        f"#define URGENT_HIGH {F.URGENT_HIGH}",
        f"#define STALE_MINUTES {F.STALE_MINUTES}",
        "",
        "/* FastLED scale8 with FASTLED_SCALE8_FIXED - the only dimming rule the goldens",
        " * and the night audit are valid for. */",
        "static inline uint8_t px_dim(uint8_t c, uint8_t factor) {",
        "    return (uint8_t)(((uint16_t)c * (factor + 1)) >> 8);",
        "}",
        "",
        "#endif /* PIXBAR_PALETTE_H */",
        "",
    ]
    return "\n".join(out)


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, text in (("fonts.h", write_fonts_h()), ("palette.h", write_palette_h())):
        path = os.path.join(OUT, name)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {path} ({len(text):,} bytes)")


if __name__ == "__main__":
    main()
